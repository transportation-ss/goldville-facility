-- Migration 058: 拆分「房間是否存在」與「是否計入會計」
-- 背景：512/513/515 的小單位子房號（512-1~512-7 等，共21間）被誤用 is_active=false
-- 同時關閉了房務指派空間，因為房務與會計共用同一個 is_active 欄位。
-- 修正：is_active 只代表房間是否存在（房務用），新增 include_in_accounting 代表是否計入會計統計。

ALTER TABLE public.rooms
  ADD COLUMN include_in_accounting boolean NOT NULL DEFAULT true;

-- 1. 救回房務空間：512/513/515 系列全部恢復可用
UPDATE public.rooms
SET is_active = true
WHERE name IN (
  '512', '512-1', '512-2', '512-3', '512-5', '512-6', '512-7',
  '513', '513-1', '513-2', '513-3', '513-5', '513-6', '513-7',
  '515', '515-1', '515-2', '515-3', '515-5', '515-6', '515-7'
);

-- 2. 子房號不計入會計（只用父房號 512/513/515 統計），避免會計出現21間重複房間
UPDATE public.rooms
SET include_in_accounting = false
WHERE name IN (
  '512-1', '512-2', '512-3', '512-5', '512-6', '512-7',
  '513-1', '513-2', '513-3', '513-5', '513-6', '513-7',
  '515-1', '515-2', '515-3', '515-5', '515-6', '515-7'
);
